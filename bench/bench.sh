#!/usr/bin/env bash
#
# bench.sh - control of the ChirpStack containers of the DownlinkScope bench.
#
# Usage: bench/bench.sh <command>
#   up        start ChirpStack (the bench network must exist: netns.sh up)
#   down      stop the containers and keep the data
#   reset     stop the containers and DELETE the ChirpStack data
#   status    show the containers
#   versions  print the exact image digests in use
#   apikey    create a ChirpStack API key and store it in bench/.api_key
#   logs      follow the logs of ChirpStack and of the gateway bridge
#
# No command needs root rights. The user must be in the 'docker' group.

set -euo pipefail

BENCH_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly BENCH_DIR
readonly CS_DIR="${BENCH_DIR}/chirpstack"
readonly ENV_FILE="${CS_DIR}/.env"
readonly API_KEY_FILE="${BENCH_DIR}/.api_key"
readonly SERVER_IP="10.10.2.2"
readonly UI_URL="http://127.0.0.1:8080"

die() {
    echo "bench.sh: error: $*" >&2
    exit 1
}

compose() {
    docker compose --project-directory "${CS_DIR}" --env-file "${ENV_FILE}" "$@"
}

ensure_env() {
    [[ -f ${ENV_FILE} ]] && return 0
    command -v openssl >/dev/null || die "openssl is needed to generate the API secret"
    # The secret signs the login and API tokens. It stays out of the repository.
    (
        umask 077
        {
            echo "# Generated by bench/bench.sh. Do not commit this file."
            echo "DLS_SERVER_IP=${SERVER_IP}"
            echo "CHIRPSTACK_API_SECRET=$(openssl rand -hex 32)"
        } >"${ENV_FILE}"
    )
    echo "created ${ENV_FILE} with a new random API secret"
}

require_env() {
    [[ -f ${ENV_FILE} ]] || die "no ${ENV_FILE}. Run 'bench/bench.sh up' first."
}

cmd_up() {
    ip -4 -o addr show | grep -q -F " ${SERVER_IP}/" ||
        die "the address ${SERVER_IP} does not exist. Run 'sudo bench/netns.sh up' first."
    ensure_env
    compose up -d
    echo -n "waiting for the ChirpStack web interface"
    local i
    for i in $(seq 1 60); do
        if curl -s -o /dev/null --max-time 2 "${UI_URL}"; then
            echo " ready (${i} s)"
            echo "web interface: ${UI_URL} (default login admin / admin, change the password)"
            return 0
        fi
        echo -n "."
        sleep 1
    done
    echo
    die "ChirpStack did not answer on ${UI_URL} in 60 s. Check 'bench/bench.sh logs'."
}

cmd_down() {
    require_env
    compose down
}

cmd_reset() {
    require_env
    compose down --volumes
    rm -f "${API_KEY_FILE}"
    echo "ChirpStack data deleted. The API key file is removed."
}

cmd_status() {
    require_env
    compose ps
}

cmd_versions() {
    require_env
    local image
    while read -r image; do
        docker image inspect --format '{{index .RepoTags 0}} {{index .RepoDigests 0}}' "${image}"
    done < <(compose config --images | sort -u)
}

cmd_apikey() {
    require_env
    local out token
    out="$(compose exec -T chirpstack chirpstack -c /etc/chirpstack create-api-key --name dls-bench 2>&1)" ||
        die "the create-api-key command failed: ${out}"
    token="$(awk '$1 == "token:" { print $2 }' <<<"${out}")"
    [[ -n ${token} ]] || die "cannot find the token in the command output: ${out}"
    (
        umask 077
        printf '%s\n' "${token}" >"${API_KEY_FILE}"
    )
    echo "API key stored in ${API_KEY_FILE} (mode 600, not in the repository)"
}

cmd_logs() {
    require_env
    compose logs --follow --tail 50 chirpstack chirpstack-gateway-bridge
}

main() {
    [[ $# -eq 1 ]] || {
        sed -n '3,14p' "$0" | sed 's/^# \{0,1\}//'
        exit 2
    }
    case "$1" in
    up) cmd_up ;;
    down) cmd_down ;;
    reset) cmd_reset ;;
    status) cmd_status ;;
    versions) cmd_versions ;;
    apikey) cmd_apikey ;;
    logs) cmd_logs ;;
    *) die "unknown command: $1" ;;
    esac
}

main "$@"
